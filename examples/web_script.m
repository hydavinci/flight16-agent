frequency_hz = params.frequency_hz;
amplitude = params.amplitude;
samples = params.samples;
t = linspace(0, 2, samples);
y = amplitude * sin(2 * pi * frequency_hz * t);
plot(t, y);
xlabel('Time (s)');
ylabel('Amplitude');
grid on;
result = struct('samples', samples, 'peak', max(y), 'minimum', min(y));
